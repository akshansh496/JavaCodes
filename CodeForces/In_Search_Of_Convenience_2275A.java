
import java.util.*;

public class In_Search_Of_Convenience_2275A {

    public static void main(String[] args) {

        Scanner sc = new Scanner(System.in);

        int t = sc.nextInt();

        while (t-- > 0) {

            int x0 = sc.nextInt();
            int y0 = sc.nextInt();
            int r = sc.nextInt();

            System.out.println((x0 + r) + " " + y0);
        }
    }
}
